export const regularCorpsIds = corpsCatalog.filter((c) => c.id !== 'ggk').map((c) => c.id);
export const ggkCampIds = new Set(['sungai-besi', 'terendak', 'sungai-udang', 'iskandar']);

export function availableCorpsForCamp(camp: Camp): string[] {
  if (!camp) return [];
  if (camp.hasGGK) return regularCorpsIds.slice();
  if (Array.isArray(camp.corpsIds) && camp.corpsIds.length > 0) return camp.corpsIds.slice();
  const hash = String(camp.id || '').split('').reduce((a, ch) => a + ch.charCodeAt(0), 0);
  const combatSets = [
    ['ramd', 'rs', 'rsd'],
    ['rrd', 'rajd', 'rad'],
    ['kad', 'rsd', 'krd'],
    ['ramd', 'rrd', 'kptd'],
    ['rs', 'rad', 'rajd'],
    ['ramd', 'rad', 'krd'],
    ['rrd', 'kad', 'rsd'],
  ];
  const service = ['kjljd', 'kkd', 'putd', 'kagat', 'kpd', 'kod', 'kpa'];
  const ids = [
    'kpa',
    'kpd',
    'kod',
    ...combatSets[hash % combatSets.length],
    service[hash % service.length],
    service[(hash + 3) % service.length],
  ];
  if (/Latihan|PUSWATAN|SIRUSA/i.test((camp.name || '') + ' ' + (camp.role || ''))) ids.push('rajd', 'rsd', 'kagat', 'kjljd');
  if (/Briged|Divisyen|Markas/i.test((camp.role || '') + ' ' + (camp.name || ''))) ids.push('ramd', 'rrd', 'kad', 'rs', 'rad', 'rajd', 'kptd', 'krd');
  if (camp.state === 'Sarawak') ids.push('rsd', 'kpd', 'kkd', 'kagat');
  if (camp.state === 'Sabah') ids.push('rs', 'kpd', 'kkd', 'putd');
  return [...new Set(ids)].filter((id) => regularCorpsIds.includes(id));
}

// Initialise camp corps
campData.forEach((c) => {
  c.hasGGK = ggkCampIds.has(c.id);
  c.corpsIds = c.hasGGK ? regularCorpsIds.slice() : availableCorpsForCamp(c);
});
for (const id of regularCorpsIds) {
  const matches = campData.filter((c) => c.corpsIds?.includes(id));
  if (matches.length < 3) {
    campData
      .filter((c) => !c.hasGGK)
      .slice(0, 3 - matches.length)
      .forEach((c) => {
        if (!c.corpsIds?.includes(id)) c.corpsIds?.push(id);
      });
  }
}

export function campById(id: string): Camp {
  return campData.find((c) => c.id === id) || campData[0];
}

export function corpsById(id: string | null): Corps | null {
  if (!id) return null;
  return corpsCatalog.find((c) => c.id === id) || null;
}

